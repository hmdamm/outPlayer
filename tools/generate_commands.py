"""
tools/generate_commands.py
Generates src/core/CommandId.h from docs/spec/hotkeys.csv.
"""

import argparse
import csv
from pathlib import Path


def cpp_escape(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def generate_header(csv_path: Path, output_path: Path) -> None:
    rows = []
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append(row)

    if not rows:
        raise ValueError(f"No rows found in {csv_path}")

    # Verify uniqueness of command_id
    cids = [r['command_id'] for r in rows]
    if len(cids) != len(set(cids)):
        raise ValueError("Duplicate command_id found in CSV!")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/generate_commands.py from docs/spec/hotkeys.csv. DO NOT EDIT DIRECTLY.",
        "#pragma once",
        "",
        "#include <QList>",
        "#include <QMetaType>",
        "#include <QString>",
        "#include <optional>",
        "#include <string_view>",
        "#include <unordered_map>",
        "",
        "namespace outplayer::core {",
        "",
        "enum class CommandId : uint16_t {",
    ]

    for r in rows:
        cid = r['command_id'].strip()
        lines.append(f"    {cid},")

    lines.extend([
        "};",
        "",
        "struct CommandInfo {",
        "    CommandId id;",
        "    QString name;",
        "    QString defaultKey;",
        "    QString defaultModifiers;",
        "    QString scope;",
        "    QString menuPath;",
        "    QString description;",
        "",
        "    bool operator==(const CommandInfo& other) const = default;",
        "};",
        "",
        "struct RawCommandData {",
        "    CommandId id;",
        "    const char* idString;",
        "    const char* name;",
        "    const char* defaultKey;",
        "    const char* defaultModifiers;",
        "    const char* scope;",
        "    const char* menuPath;",
        "    const char* description;",
        "};",
        "",
        "inline constexpr RawCommandData kRawCommandData[] = {",
    ])

    for r in rows:
        cid = r['command_id'].strip()
        fn_name = cpp_escape(r['function_name'].strip())
        key = cpp_escape(r['key'].strip())
        modifiers = cpp_escape(r['modifiers'].strip())
        scope = cpp_escape(r['scope'].strip())
        menu_path = cpp_escape(r['menu_path'].strip())
        desc = fn_name  # description defaults to function_name

        lines.append(
            f'    {{ CommandId::{cid}, "{cid}", "{fn_name}", "{key}", "{modifiers}", "{scope}", "{menu_path}", "{desc}" }},'
        )

    lines.extend([
        "};",
        "",
        "inline constexpr size_t TotalCommands = sizeof(kRawCommandData) / sizeof(kRawCommandData[0]);",
        "",
        "[[nodiscard]] inline QString commandIdToString(CommandId id) {",
        "    switch (id) {",
    ])

    for r in rows:
        cid = r['command_id'].strip()
        lines.append(f'    case CommandId::{cid}: return QStringLiteral("{cid}");')

    lines.extend([
        "    }",
        "    return {};",
        "}",
        "",
        "[[nodiscard]] inline std::optional<CommandId> stringToCommandId(std::string_view str) {",
        "    static const std::unordered_map<std::string_view, CommandId> s_map = {",
    ])

    for r in rows:
        cid = r['command_id'].strip()
        lines.append(f'        {{ "{cid}", CommandId::{cid} }},')

    lines.extend([
        "    };",
        "    if (const auto it = s_map.find(str); it != s_map.end()) {",
        "        return it->second;",
        "    }",
        "    return std::nullopt;",
        "}",
        "",
        "[[nodiscard]] inline std::optional<CommandId> stringToCommandId(const QString& str) {",
        "    const auto utf8 = str.toUtf8();",
        "    return stringToCommandId(std::string_view(utf8.constData(), static_cast<size_t>(utf8.size())));",
        "}",
        "",
        "[[nodiscard]] inline QList<CommandInfo> createDefaultCommandCatalog() {",
        "    QList<CommandInfo> list;",
        "    list.reserve(static_cast<qsizetype>(TotalCommands));",
        "    for (const auto& raw : kRawCommandData) {",
        "        list.append(CommandInfo{",
        "            .id = raw.id,",
        "            .name = QString::fromUtf8(raw.name),",
        "            .defaultKey = QString::fromUtf8(raw.defaultKey),",
        "            .defaultModifiers = QString::fromUtf8(raw.defaultModifiers),",
        "            .scope = QString::fromUtf8(raw.scope),",
        "            .menuPath = QString::fromUtf8(raw.menuPath),",
        "            .description = QString::fromUtf8(raw.description),",
        "        });",
        "    }",
        "    return list;",
        "}",
        "",
        "} // namespace outplayer::core",
        "",
        "Q_DECLARE_METATYPE(outplayer::core::CommandId)",
        "",
    ])

    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {output_path} with {len(rows)} commands.")


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description="Generate CommandId.h from hotkeys.csv")
    parser.add_argument(
        "--input",
        type=Path,
        default=repo_root / "docs" / "spec" / "hotkeys.csv",
        help="Path to hotkeys.csv",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=repo_root / "src" / "core" / "CommandId.h",
        help="Path to output CommandId.h",
    )
    args = parser.parse_args()
    generate_header(args.input, args.output)


if __name__ == "__main__":
    main()
